#!/usr/bin/env python3
"""
Sync public GitHub repositories for portfolio into _data/repositories.yml.
Run anytime with: make sync (or python3 sync_repos.py)
"""

import urllib.request
import json
import os
import sys

SITE_DIR = os.path.dirname(os.path.abspath(__file__))
CONFIG_FILE = os.path.join(SITE_DIR, '_config.yml')
DATA_DIR = os.path.join(SITE_DIR, '_data')
DATA_FILE = os.path.join(DATA_DIR, 'repositories.yml')

def get_github_username():
    """Extract github_username from _config.yml."""
    if os.path.exists(CONFIG_FILE):
        with open(CONFIG_FILE, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line.startswith('github_username:'):
                    return line.split(':', 1)[1].strip().strip('"').strip("'")
    return 'zkalves'

def fetch_repositories(username):
    url = f"https://api.github.com/users/{username}/repos?per_page=100&sort=updated"
    req = urllib.request.Request(
        url,
        headers={
            'User-Agent': f'{username}-portfolio-sync',
            'Accept': 'application/vnd.github.v3+json'
        }
    )

    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode('utf-8'))
    except urllib.error.HTTPError as e:
        print(f"Error: GitHub API responded with HTTP {e.code}: {e.reason}", file=sys.stderr)
        if e.code == 403:
            print("Note: GitHub unauthenticated rate limit reached (60 req/hr). Try again later.", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Error connecting to GitHub API: {e}", file=sys.stderr)
        sys.exit(1)

    if not isinstance(data, list):
        print("Error: Unexpected response format from GitHub API.", file=sys.stderr)
        sys.exit(1)

    portfolio_repo = f"{username}.github.io".lower()

    # Filter out forks and portfolio site repository
    filtered = []
    for r in data:
        if r.get('fork', False):
            continue
        name = (r.get('name') or '').strip()
        if not name or name.lower() == portfolio_repo:
            continue
        filtered.append({
            'name': name,
            'html_url': r.get('html_url', f"https://github.com/{username}/{name}"),
            'description': (r.get('description') or '').strip() or 'No description provided.',
            'language': (r.get('language') or '').strip() or 'Other',
            'stargazers_count': int(r.get('stargazers_count') or 0),
            'updated_at': r.get('updated_at', ''),
            'pushed_at': r.get('pushed_at', '')
        })

    # Sort by stars descending, then last pushed
    filtered.sort(
        key=lambda x: (x['stargazers_count'], x['pushed_at']),
        reverse=True
    )
    return filtered

def escape_yaml_string(s):
    """Safely format string for YAML output."""
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ')
    return f'"{s}"'

def save_to_yaml(repos):
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(DATA_FILE, 'w', encoding='utf-8') as f:
        f.write("# Automatically generated by sync_repos.py\n")
        f.write("# Run 'make sync' to update\n\n")
        if not repos:
            f.write("[]\n")
            return

        for r in repos:
            f.write(f"- name: {escape_yaml_string(r['name'])}\n")
            f.write(f"  html_url: {escape_yaml_string(r['html_url'])}\n")
            f.write(f"  description: {escape_yaml_string(r['description'])}\n")
            f.write(f"  language: {escape_yaml_string(r['language'])}\n")
            f.write(f"  stargazers_count: {r['stargazers_count']}\n")
            f.write(f"  updated_at: {escape_yaml_string(r['updated_at'])}\n\n")

def main():
    username = get_github_username()
    print(f"Fetching public repositories for '{username}' from GitHub...")
    repos = fetch_repositories(username)
    save_to_yaml(repos)
    print(f"✓ Successfully synchronized {len(repos)} repositories to _data/repositories.yml")
    for r in repos:
        print(f"  • {r['name']} ({r['language']}) - {r['description'][:60]}...")
    print("\nYou can now run 'git diff' to review and 'git commit' whenever needed.")

if __name__ == '__main__':
    main()
